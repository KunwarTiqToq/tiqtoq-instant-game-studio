import test from 'node:test';
import assert from 'node:assert/strict';
import {once} from 'node:events';
import type {AddressInfo} from 'node:net';
import {MongoClient} from 'mongodb';
import {MongoMemoryReplSet} from 'mongodb-memory-server';
import {initializeDatabase} from '../src/db/database.js';
import {LiveOpsService} from '../src/domain/service.js';
import {createCoreServer} from '../src/server.js';

test('GET clears every user collection, preserves indexes, and can be repeated', {timeout:120000}, async(t)=>{
  const mongo=await MongoMemoryReplSet.create({replSet:{count:1},binary:{version:'7.0.14'}});
  const client=new MongoClient(mongo.getUri());
  const db=client.db('clear_demo_test');
  const core=createCoreServer(new LiveOpsService(client,db));
  t.after(async()=>{await core.close();await client.close();await mongo.stop();});
  await initializeDatabase(client,db);
  const names=(await db.listCollections().toArray()).map(c=>c.name);
  for(const name of names) await db.collection(name).insertOne({demo:true});
  await db.collection('additionalDemoRecords').insertMany([{demo:1},{demo:2}]);
  const originalIndexes=await db.collection('awards').indexes();
  core.server.listen(0,'127.0.0.1');await once(core.server,'listening');
  const url=`http://127.0.0.1:${(core.server.address() as AddressInfo).port}/clear-db`;
  assert.equal((await fetch(url,{method:'HEAD'})).status,405);
  assert.equal(await db.collection('players').countDocuments(),1);
  const response=await fetch(url);assert.equal(response.status,200);assert.equal(response.headers.get('cache-control'),'no-store');
  const result=await response.json() as {database:string;deletedCount:number;collections:Record<string,number>};
  assert.equal(result.database,'clear_demo_test');assert.equal(result.deletedCount,names.length+2);
  assert.equal(result.collections.additionalDemoRecords,2);
  for(const collection of await db.listCollections().toArray()) assert.equal(await db.collection(collection.name).countDocuments(),0);
  assert.deepEqual(await db.collection('awards').indexes(),originalIndexes);
  assert.equal(((await (await fetch(url)).json()) as {deletedCount:number}).deletedCount,0);
});
