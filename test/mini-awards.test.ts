import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import type { AddressInfo } from 'node:net';
import test from 'node:test';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import { MongoClient } from 'mongodb';
import WebSocket from 'ws';
import { initializeDatabase } from '../src/db/database.js';
import { LiveOpsService } from '../src/domain/service.js';
import { createCoreServer } from '../src/server.js';

test('one-time mini-game awards and targeted server push', { timeout: 120000 }, async (t) => {
  const mongo = await MongoMemoryReplSet.create({ replSet: { count: 1 }, binary: { version: '7.0.14' } });
  const client = new MongoClient(mongo.getUri());
  const db = client.db('mini_awards_test'); await initializeDatabase(client,db);
  const service = new LiveOpsService(client,db);
  const core = createCoreServer(service);
  t.after(async()=>{await core.close();await client.close();await mongo.stop();});
  const player=await service.createPlayer({displayName:'Bonus player',balance:100,tags:['vip']});
  const other=await service.createPlayer({displayName:'Other',balance:100,tags:[]});
  const audience={playerIds:[player._id],tags:[],minBalance:0,maxBalance:1000000,minDeposits:0};
  await t.test('snapshot, concurrent redemption, ownership, revocation, and exact multiplier credit',async()=>{
    const config={mode:'multiplier' as const,baseAmount:10,prizes:[{amount:3},{amount:3},{amount:3}]};
    const campaign=await service.createCampaign({name:'Chests',description:'',status:'active',rewardType:'chests',rewardValue:1,audience,gameConfig:config});
    await service.issueCampaign(campaign._id);
    const award=(await service.c.awards.findOne({campaignId:campaign._id}))!;
    await service.updateCampaign(campaign._id,{name:'Edited',description:'',status:'active',rewardType:'chests',rewardValue:1,audience,gameConfig:{...config,baseAmount:100}});
    assert.equal((await service.getAward(player._id,award._id)).gameConfig.baseAmount,10);
    await assert.rejects(service.playAward(other._id,award._id,0),/not found/);
    await assert.rejects(service.playAward(player._id,award._id,9),/valid game item/);
    const [a,b]=await Promise.all([service.playAward(player._id,award._id,0),service.playAward(player._id,award._id,1)]);
    assert.equal(a.status,'played');assert.deepEqual(a.outcome,b.outcome);assert.equal(a.outcome?.payout,30);
    assert.equal((await service.getPlayer(player._id)).balance,130);
    assert.deepEqual((await service.playAward(player._id,award._id,2)).outcome,a.outcome);
    await assert.rejects(service.revoke(award._id),/Only pending/);
    const revoked=await service.grant({playerId:player._id,type:'wheel',value:1,requestId:'revoked',gameConfig:config});
    await service.revoke(revoked._id);await assert.rejects(service.playAward(player._id,revoked._id),/no longer available/);
    assert.equal((await service.getPlayer(player._id)).balance,130);
    assert.equal((await service.analytics()).awards.miniGamePayout,30);
  });
  await t.test('new games settle once and persist reveal layouts across competing choices',async()=>{
    for (const type of ['scratch'] as const) {
      const config={mode:'multiplier' as const,baseAmount:10,prizes:[{amount:2},{amount:2},{amount:2}]};
      const before=(await service.getPlayer(player._id)).balance;
      const award=await service.grant({playerId:player._id,type,value:1,requestId:randomUUID(),gameConfig:config});
      assert.ok((await service.pendingAwards(player._id)).some((a)=>a._id === award._id));
      const [a,b]=await Promise.all([service.playAward(player._id,award._id,0),service.playAward(player._id,award._id,2)]);
      assert.deepEqual(a.outcome,b.outcome);
      if (type === 'scratch') assert.equal(a.outcome!.revealedPrizes![a.outcome!.choiceIndex!],a.outcome!.prizeIndex);
      assert.equal((await service.getPlayer(player._id)).balance,before+20);
      assert.deepEqual((await service.getAward(player._id,award._id)).outcome,a.outcome);
    }
  });
  await t.test('timed targets sum unique hits, resume the original deadline, and settle once at expiry',async()=>{
    const config={mode:'multiplier' as const,baseAmount:10,durationSeconds:5,targetRange:{min:2,max:2},prizes:[{amount:2},{amount:2},{amount:2}]};
    const award=await service.grant({playerId:player._id,type:'targets',value:1,requestId:randomUUID(),gameConfig:config});
    const before=(await service.getPlayer(player._id)).balance;
    await assert.rejects(service.playAward(player._id,award._id,0),/timed target/);
    await assert.rejects(service.targetAction(other._id,award._id,'start'),/not found/);
    const started=await service.targetAction(player._id,award._id,'start');
    assert.equal(started.targetRound!.activeIds.length,3);
    assert.equal((await service.targetAction(player._id,award._id,'start')).targetRound!.endsAt,started.targetRound!.endsAt);
    await assert.rejects(service.revoke(award._id),/not started/);
    const [a,b]=await Promise.all([service.targetAction(player._id,award._id,'hit',started.targetRound!.activeIds[0]),service.targetAction(player._id,award._id,'hit',started.targetRound!.activeIds[0])]);
    assert.equal(a.targetRound!.hits.length,1);assert.deepEqual(a.targetRound,b.targetRound);
    const hit=await service.targetAction(player._id,award._id,'hit',a.targetRound!.activeIds[0]);
    assert.equal(hit.targetRound!.amount,4);assert.equal(hit.targetRound!.payout,40);
    assert.equal((await service.targetAction(player._id,award._id,'finish')).status,'pending');
    assert.equal((await service.getPlayer(player._id)).balance,before);
    await assert.rejects(service.targetAction(player._id,award._id,'hit','invented'),/not active/);
    await service.c.awards.updateOne({_id:award._id},{$set:{'targetRound.endsAt':Date.now()-1}});
    const [finished,retry]=await Promise.all([service.targetAction(player._id,award._id,'hit',hit.targetRound!.activeIds[1]),service.targetAction(player._id,award._id,'finish')]);
    assert.deepEqual(finished.outcome,retry.outcome);assert.equal(finished.outcome!.payout,40);assert.equal(finished.outcome!.hitCount,2);
    assert.equal((await service.getPlayer(player._id)).balance,before+40);
    const empty=await service.grant({playerId:player._id,type:'targets',value:1,requestId:randomUUID(),gameConfig:config});
    await service.targetAction(player._id,empty._id,'start');
    await service.c.awards.updateOne({_id:empty._id},{$set:{'targetRound.endsAt':Date.now()-1}});
    await service.settleExpiredTargets();
    assert.equal((await service.getAward(player._id,empty._id)).outcome!.payout,0);
  });
  core.server.listen(0,'127.0.0.1');await once(core.server,'listening');
  const port=(core.server.address() as AddressInfo).port;
  const connect=async()=>{const socket=new WebSocket(`ws://127.0.0.1:${port}/ws/games`);await once(socket,'open');t.after(()=>socket.terminate());return socket;};
  const request=(socket:WebSocket,message:Record<string,unknown>)=>new Promise<Record<string,any>>((resolve)=>{
    const listener=(data:WebSocket.RawData)=>{const m=JSON.parse(data.toString());if(m.requestId===message.requestId){socket.off('message',listener);resolve(m);}};
    socket.on('message',listener);socket.send(JSON.stringify(message));
  });
  await t.test('push targets the matching player and reconnect restores pending awards',async()=>{
    const socket=await connect();const outsider=await connect();
    await request(socket,{type:'session.open',requestId:'session',playerId:player._id,token:player.gameToken});
    await request(outsider,{type:'session.open',requestId:'other-session',playerId:other._id,token:other.gameToken});
    let otherNotifications=0;outsider.on('message',(data)=>{if(JSON.parse(data.toString()).type==='awards.updated')otherNotifications++;});
    const pushed=new Promise<Record<string,any>>((resolve)=>{const listener=(data:WebSocket.RawData)=>{const m=JSON.parse(data.toString());if(m.type==='awards.updated'&&m.awards.length){socket.off('message',listener);resolve(m);}};socket.on('message',listener);});
    const config={mode:'instant' as const,prizes:[{amount:7},{amount:7}]};
    const campaign=await service.createCampaign({name:'Push wheel',description:'',status:'active',rewardType:'wheel',rewardValue:1,audience:{...audience,playerIds:[],tags:['vip']},gameConfig:config});
    await service.issueCampaign(campaign._id);
    const received=await pushed;assert.equal(received.awards.length,1);assert.equal(otherNotifications,0);
    const awardId=received.awards[0].id;
    assert.equal((await request(outsider,{type:'award.get',requestId:'forbidden',awardId})).error.code,'AWARD_NOT_FOUND');
    const reconnect=await connect();
    const restored=await request(reconnect,{type:'session.open',requestId:'reconnect',playerId:player._id,token:player.gameToken});
    assert.equal(restored.awards[0].id,awardId);
    const before=(await service.getPlayer(player._id)).balance;
    const preview=await request(socket,{type:'mini.preview',requestId:'preview',game:'wheel',config});assert.equal(preview.outcome.payout,7);
    assert.equal((await service.getPlayer(player._id)).balance,before);
    const tampered=await request(socket,{type:'award.play',requestId:'tampered',awardId,config:{mode:'instant',prizes:[{amount:999},{amount:999}]}});
    assert.equal(tampered.error.code,'INVALID_MESSAGE');
    const won=await request(socket,{type:'award.play',requestId:'award-once',awardId});assert.equal(won.award.outcome.payout,7);
    const duplicate=await request(reconnect,{type:'award.play',requestId:randomUUID(),awardId});assert.deepEqual(duplicate.award.outcome,won.award.outcome);
    assert.equal((await service.getPlayer(player._id)).balance,before+7);assert.equal((await service.pendingAwards(player._id)).length,0);
    const timed=await service.grant({playerId:player._id,type:'targets',value:1,requestId:randomUUID(),gameConfig:{mode:'instant',durationSeconds:5,targetRange:{min:3,max:3},prizes:[{amount:3},{amount:3},{amount:3}]}});
    const started=await request(socket,{type:'targets.start',requestId:randomUUID(),awardId:timed._id});
    const shot=await request(socket,{type:'targets.hit',requestId:randomUUID(),awardId:timed._id,targetId:started.award.targetRound.activeIds[0]});
    assert.equal(shot.award.targetRound.payout,3);
    const resumed=await request(reconnect,{type:'targets.start',requestId:randomUUID(),awardId:timed._id});
    assert.equal(resumed.award.targetRound.endsAt,started.award.targetRound.endsAt);
    await service.c.awards.updateOne({_id:timed._id},{$set:{'targetRound.endsAt':Date.now()-1}});
    const settled=await request(socket,{type:'targets.finish',requestId:randomUUID(),awardId:timed._id});
    assert.equal(settled.award.outcome.payout,3);assert.equal(settled.award.status,'played');
    socket.close();outsider.close();reconnect.close();
  });
});
